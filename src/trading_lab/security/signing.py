"""Ed25519 signing for approval artifacts (architecture §6.4).

*** TEST-ONLY IN M0 ***

All key material handled by this module in M0 is generated by
:func:`generate_test_keypair` for unit tests and smoke runs with fictional
accounts. In production the signer runs on the owner's isolated
terminal/HSM (non-Agent-accessible); the platform never requests, stores or
transmits private keys. Replacing the trust root is verified to be rejected
by the verifier's key-ID pinning (see tests/security/test_verifier.py).

Signature covers the canonical JSON bytes of the payload (see canonical.py).
"""

from __future__ import annotations

import base64
from dataclasses import dataclass

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey

from .canonical import canonical_json_bytes, sha256_hex

SIGNATURE_ALGORITHM = "Ed25519"


@dataclass(frozen=True)
class TestKeyPair:
    """A generated key pair. ``key_id`` is the first 16 hex chars of
    SHA-256(canonical public key bytes) — the verifier pins trust to this
    identifier, so a self-built key with a different ID can never be
    substituted for a trusted one."""

    private_pem: bytes
    public_pem: bytes
    key_id: str

    @staticmethod
    def key_id_for_public_pem(public_pem: bytes) -> str:
        pub = serialization.load_pem_public_key(public_pem)
        raw = pub.public_bytes(
            encoding=serialization.Encoding.Raw,
            format=serialization.PublicFormat.Raw,
        )
        return sha256_hex(raw)[:16]


def generate_test_keypair() -> TestKeyPair:
    """Generate a fresh Ed25519 key pair for tests/mock dry-runs.

    TEST-ONLY: real approval keys never pass through this code path; they
    live in the owner's isolated signing environment and only their public
    halves (with pinned key_ids) are deployed to the runtime out-of-band.
    """
    priv = Ed25519PrivateKey.generate()
    private_pem = priv.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )
    pub = priv.public_key()
    public_pem = pub.public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )
    return TestKeyPair(
        private_pem=private_pem,
        public_pem=public_pem,
        key_id=TestKeyPair.key_id_for_public_pem(public_pem),
    )


def sign_payload(private_pem: bytes, payload: object) -> str:
    """Sign the canonical JSON form of ``payload``; returns base64 signature."""
    key = serialization.load_pem_private_key(private_pem, password=None)
    if not isinstance(key, Ed25519PrivateKey):
        raise ValueError("signing key must be an Ed25519 private key")
    sig = key.sign(canonical_json_bytes(payload))
    return base64.b64encode(sig).decode("ascii")


def verify_signature(public_pem: bytes, payload: object, signature_b64: str) -> bool:
    """Verify a base64 Ed25519 signature over the canonical JSON form of
    ``payload``. Returns False (never raises) on any mismatch/invalid input,
    so callers can treat False uniformly as fail-closed."""
    try:
        pub = serialization.load_pem_public_key(public_pem)
        if not isinstance(pub, Ed25519PublicKey):
            return False
        raw_sig = base64.b64decode(signature_b64, validate=True)
        pub.verify(raw_sig, canonical_json_bytes(payload))
        return True
    except (InvalidSignature, ValueError, TypeError):
        return False


